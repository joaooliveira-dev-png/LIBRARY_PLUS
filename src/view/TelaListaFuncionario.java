    private void btAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAtualizarActionPerformed
        int linhaSelecionada = tabelaFuncionario.getSelectedRow();
        
        if(linhaSelecionada  == -1){
            JOptionPane.showMessageDialog(this, "Selecione um livro para atualizar");
            return;
        }
        
        int id = (int) tabelaFuncionario.getValueAt(linhaSelecionada, 0);
        
        Funcionario funcionario = controller.buscarPorId(id);
        
        if(funcionario == null){
            JOptionPane.showMessageDialog(this, "Usuario não encontrado");
            return;
        }
        
        TelaCadastroFuncionario tela = new TelaCadastroFuncionario(funcionario);
        tela.setVisible(true);
        dispose();
    }//GEN-LAST:event_btAtualizarActionPerformed

    private void btBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btBuscarActionPerformed
        if(txtBuscarID.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe o ID do livro");
            txtBuscarID.requestFocus();
            return;
        }
        
        try {

            int id = Integer.parseInt(txtBuscarID.getText().trim());

            Funcionario fun = controller.buscarPorId(id);

            DefaultTableModel modelo =
                    (DefaultTableModel) tabelaFuncionario.getModel();

            modelo.setRowCount(0);

            if (fun != null) {

                modelo.addRow(new Object[]{
                    fun.getId(),
                    fun.getNome(),
                    fun.getCargo(),
                    fun.getUsuario(),
                });

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Livro não encontrado."
                );
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "Informe um ID válido."
            );
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btBuscarActionPerformed

    private void btExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btExcluirActionPerformed
                int linhaSelecionada = tabelaFuncionario.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(
                this,
                "Selecione um funcionário para excluir."
            );
            return;
        }

        int id = (int) tabelaFuncionario.getValueAt(linhaSelecionada, 0);

        int confirmacao = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este Funcionário?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
        );

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        controller.excluir(id);

        JOptionPane.showMessageDialog(
            this,
            "Funcionário excluído com sucesso!"
        );

        carregarFuncionario();
    }//GEN-LAST:event_btExcluirActionPerformed

