    public void carregarFuncionario(){
        
        List<Funcionario> funcionarios = controller.listar();
        
        DefaultTableModel model = (DefaultTableModel) tabelaFuncionario.getModel();
        
        model.setRowCount(0);
        
        for (Funcionario f : funcionarios){
            model.addRow(new Object[]{
                f.getId(),
                f.getNome(),
                f.getCargo(),
                f.getUsuario(),
            });
        }
    }
    
